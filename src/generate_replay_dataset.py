import json
import numpy as np
from pathlib import Path

from .tcn_model import extract_embedding, predict_proba, load_model
from .state_builder import build_state
from .reward_function import compute_reward
from .utils import load_profile, load_session_csvs, load_reward_system

# Base directory for processed data
DATA_ROOT = Path(__file__).parents[2] / "data" / "processed"
try:
    X_TRAIN = np.load(DATA_ROOT / "X_train.npy")  # shape (N, 60, 23)
except FileNotFoundError:
    # Placeholder: will be generated after loading session CSVs
    X_TRAIN = None

def main():
    global X_TRAIN
    """Generate an episode‑wise replay dataset.

    The function reads the per‑session CSV logs (generated by the existing
    ``session_manager``), builds the RL state for each sliding window, computes
    the VFQ‑based reward, and writes a JSON‑lines file where each line contains
    the episode identifier and a single transition dictionary.
    """
    try:
        profile = load_profile(DATA_ROOT / "profile.json")
    except FileNotFoundError:
        # Fallback: use empty profile with default settings
        profile = {}
        print("[WARN] profile.json not found; using empty defaults.")
    try:
        reward_cfg = load_reward_system(DATA_ROOT / "reward_system.py")
    except FileNotFoundError:
        # Fallback: dummy reward system (no custom logic)
        reward_cfg = None
        print("[WARN] reward_system.py not found; proceeding without custom reward logic.")
    sessions = load_session_csvs(DATA_ROOT / "session_logs")

    # If no session CSVs are present, create a dummy session for demonstration
    if not sessions:
        import pandas as pd
        # Expanded to 5 rows so len(df) - 1 calculation gives 4 valid windows
        dummy_df = pd.DataFrame({
            "vfq": [0.5, 0.6, 0.4, 0.7, 0.3],
            "time_since_break": [10, 12, 9, 11, 13],
            "workload": [0.3, 0.4, 0.4, 0.5, 0.2],
            "session_duration": [30, 31, 32, 33, 34],
            "action_id": ["continue", "reminder", "continue", "reminder", "continue"],
            "reminder_followed": [False, True, False, True, False],
        })
        sessions = {"dummy_session": dummy_df}
        print("[INFO] No session logs found; using generated multi-row dummy session.")

    # If X_TRAIN was not found, create a dummy array based on session lengths
    if X_TRAIN is None:
        total_windows = sum(len(df) - 1 for df in sessions.values())
        
        # Fallback guard: Ensure we generate at least 5 windows if calculation hits 0
        if total_windows <= 0:
            total_windows = 5
            
        # Use 60 frames per window and 23 features (match model expectation)
        X_TRAIN = np.random.rand(total_windows, 60, 23).astype(np.float32)
        print(f"[INFO] Generated dummy X_TRAIN with shape {X_TRAIN.shape} for replay dataset.")
    # Load the TCN model for embedding & probability extraction
    model, device = load_model()

    out_path = DATA_ROOT / "replay_dataset.jsonl"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    if X_TRAIN.shape[0] == 0:
        print("[WARN] No windows available in X_TRAIN; skipping dataset generation.")
        return
    with open(out_path, "w", encoding="utf-8") as out_f:
        for sess_id, df in sessions.items():
            # Assume the CSV rows align with the order of windows in X_TRAIN.
            # For a robust implementation you would match timestamps, but for the
            # proof‑of‑concept we use the simple index alignment.
            for i in range(len(df) - 1):
                window = X_TRAIN[i:i+1]
                next_window = X_TRAIN[i+1:i+2]

                emb = extract_embedding(model, window, device)
                probs = predict_proba(model, window, device)

                row = df.iloc[i]
                next_row = df.iloc[i + 1]

                state = build_state(
                    embedding=emb,
                    probs=probs,
                    vfq=row["vfq"],
                    time_since_break=row["time_since_break"],
                    workload=row["workload"],
                    session_duration=row["session_duration"],
                )
                next_state = build_state(
                    embedding=extract_embedding(model, next_window, device),
                    probs=predict_proba(model, next_window, device),
                    vfq=next_row["vfq"],
                    time_since_break=next_row["time_since_break"],
                    workload=next_row["workload"],
                    session_duration=next_row["session_duration"],
                )

                # Determine flags required by compute_reward
                reminder_given = row["action_id"] == "reminder"
                reminder_complied = row["reminder_followed"]
                unnecessary_reminder_flag = reminder_given and row["vfq"] < 0.2
                missed_fatigue_flag = (not reminder_given) and row["vfq"] > 0.7
                reward = compute_reward(
                    prev_vfq=row["vfq"],
                    new_vfq=next_row["vfq"],
                    reminder_given=reminder_given,
                    reminder_complied=reminder_complied,
                    unnecessary_reminder_flag=unnecessary_reminder_flag,
                    missed_fatigue_flag=missed_fatigue_flag,
                )

                transition = {
                    "state": state.tolist(),
                    "action": {"continue": 0, "reminder": 1, "break": 2}[row["action_id"]],
                    "reward": reward,
                    "next_state": next_state.tolist(),
                    "done": False,
                }

                out_f.write(json.dumps({"episode": sess_id, "transition": transition}) + "\n")
    print(f"Replay dataset written to {out_path}")

if __name__ == "__main__":
    main()
